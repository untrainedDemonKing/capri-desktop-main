#!/usr/bin/env python3
"""Builds src/renderer/js/voice-stress-data.js: where the stress falls in Russian words, for her own voice.

Russian stress is not predictable from spelling, so her voice (voice-phones.js) uses three things, best first:
  1. a list of the most common spoken words with their stress, (the exceptions to 2: only the words the
     rules below get wrong are stored)
  2. a decision list on word endings ("-ть: the last vowel but one"), learned from those words, right
     about 72% of the time on words it has not seen (51% for "always the one before the last")
  3. the one before the last.
This script makes 1 and 2. It needs espeak-ng, installed on the machine running it (dev time only: the
app never uses it) and a word list by frequency (conversational Russian, one "word count" per line,
e.g. FrequencyWords ru_50k.txt). The stress of every word is read from espeak-ng once, here, and the
few words it gets wrong are fixed by hand (FIXES below). Run:

  python3 tools/build-voice-stress.py path/to/ru_50k.txt
"""
import collections, json, os, re, subprocess, sys
from multiprocessing.pool import ThreadPool

RV = 'аеёиоуыэюя'
IPA_VOWELS = set('aɑɐəɪɨɵʌʊɛeiouyæɔɜɚ')
TOP = 12000      # how many of the most common words are stored (when the rules get them wrong)
LEARN = 40000    # how many words the endings are learned from
MAXLEN, MINSUP, MINPUR = 5, 6, 0.6
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'src', 'renderer', 'js', 'voice-stress-data.js')

# words espeak-ng gets wrong (checked by hand), stressed vowel in capitals
FIXES = ('тебЕ себЕ моЯ моЮ делА глазА уходИт сЕрвера перезапустИ записАла').split()

def vowels(w): return [i for i, c in enumerate(w) if c in RV]

def label(words):
    def one(w):
        ipa = subprocess.run(['espeak-ng', '-v', 'ru', '-q', '--ipa', w], capture_output=True, text=True).stdout.strip().replace('\n', ' ')
        if 'ˈ' not in ipa or ' ' in ipa: return w, None
        pos = sum(1 for ch in ipa.split('ˈ')[0] if ch in IPA_VOWELS)
        if sum(1 for ch in ipa if ch in IPA_VOWELS) != len(vowels(w)): return w, None
        return w, pos
    return {w: p for w, p in ThreadPool(8).map(one, words) if p is not None}

def main(freq_path):
    words = []
    for line in open(freq_path, encoding='utf8'):
        w = line.split()[0]
        if re.fullmatch(r'[а-яё]+', w) and len(w) >= 3 and len(vowels(w)) >= 2 and 'ё' not in w: words.append(w)
    words = words[:LEARN]
    # the project's own words too (what she says in Russian)
    own = set()
    for rel in ('src/renderer/js/lines.js', 'src/renderer/js/lines-life.js', 'README.md'):
        p = os.path.join(HERE, '..', rel)
        if os.path.exists(p): own |= {w for w in re.findall(r'[а-яё]+', open(p, encoding='utf8').read().lower()) if len(w) >= 3 and len(vowels(w)) >= 2 and 'ё' not in w}
    todo = list(dict.fromkeys(words + sorted(own - set(words))))
    idx = label(todo)
    for f in FIXES:
        up = [i for i, c in enumerate(f) if c != c.lower()]
        if up: idx[f.lower()] = vowels(f.lower()).index(up[0])
        else: idx.pop(f.lower(), None)  # a word with no capital: drop espeak's answer, let the rules decide
    # learn: ending -> how many vowels from the end the stress is
    cnt = collections.defaultdict(collections.Counter)
    for w in words:
        if w not in idx: continue
        n = len(vowels(w))
        for L in range(1, MAXLEN + 1):
            if len(w) > L: cnt[w[-L:]][n - 1 - idx[w]] += 1
    rules = {}
    for suf, c in cnt.items():
        tot = sum(c.values()); off, k = c.most_common(1)[0]
        if tot >= MINSUP and k / tot >= MINPUR: rules[suf] = off
    def by_rules(w):
        n = len(vowels(w))
        for L in range(min(MAXLEN, len(w) - 1), 0, -1):
            off = rules.get(w[-L:])
            if off is not None: return max(0, min(n - 1, n - 1 - off))
        return max(0, n - 2)
    common = [w for w in words[:TOP] if w in idx] + [w for w in sorted(own) if w in idx and w not in words[:TOP]]
    wrong = [w for w in common if by_rules(w) != idx[w]]
    def mark(w): i = vowels(w)[idx[w]]; return w[:i] + w[i].upper() + w[i + 1:]
    rule_str = ' '.join(f'{s}{o}' for s, o in sorted(rules.items(), key=lambda kv: (len(kv[0]), kv[0])))
    word_str = ' '.join(mark(w) for w in wrong)
    held = [w for w in words[TOP:] if w in idx]
    acc = sum(by_rules(w) == idx[w] for w in held) / max(1, len(held))
    with open(OUT, 'w', encoding='utf8') as f:
        f.write('// Generated by tools/build-voice-stress.py. Do not edit: run it again.\n'
                '// STRESS_RULES: ending + how many vowels from the end the stress falls on (longest ending wins).\n'
                '// STRESS_WORDS: common words the endings get wrong, the stressed vowel in capitals.\n')
        f.write('export const STRESS_RULES = ' + json.dumps(rule_str, ensure_ascii=False) + ';\n')
        f.write('export const STRESS_WORDS = ' + json.dumps(word_str, ensure_ascii=False) + ';\n')
    print(f'{len(idx)} words read, {len(rules)} ending rules, {len(wrong)} stored words, rules right on {acc:.1%} of the rarer words')
    print(f'{os.path.getsize(OUT) // 1024} KB written to {os.path.relpath(OUT)}')

if __name__ == '__main__':
    if len(sys.argv) < 2: sys.exit(__doc__)
    main(sys.argv[1])
