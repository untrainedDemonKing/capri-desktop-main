function text(lang, key, args = {}) {
  const table = LINES[lang] || LINES.en;
  const raw = table[key] ?? LINES.en[key] ?? key;
  return raw.replace(/\{(\w+)\}/g, (_m, name) => (args[name] === undefined || args[name] === null ? '' : String(args[name])));
}

const table = (lang) => ({ ...LINES.en, ...(LINES[lang] || {}) });

module.exports = { text, table, LINES };
