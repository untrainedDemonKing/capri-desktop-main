  ttsKeyPage: (engine) => ipcRenderer.send('tts:keyPage', engine),
  chatterboxStatus: () => ipcRenderer.invoke('chatterbox:status'),
  chatterboxChoose: () => ipcRenderer.invoke('chatterbox:choose'),
  chatterboxRestart: () => ipcRenderer.invoke('chatterbox:restart'),
  voiceSample: () => ipcRenderer.invoke('voice:sample'),
  voiceSampleChoose: () => ipcRenderer.invoke('voice:sampleChoose'),
  voiceSampleRemove: () => ipcRenderer.invoke('voice:sampleRemove'),
  piperVoices: () => ipcRenderer.invoke('piper:voices'),
  onChatterbox: on('chatterbox:status'),
  piperStatus: () => ipcRenderer.invoke('piper:status'),
  onPiper: on('piper:status'),
  ollamaStatus: () => ipcRenderer.invoke('ollama:status'),
  onOllama: on('ollama:status'),
  provisionStatus: () => ipcRenderer.invoke('provision:status'),
  onProvision: on('provision:status'),
  prepareShow: () => ipcRenderer.send('prepare:show'),
